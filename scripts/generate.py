"""Write generated company packs and scenarios from their specs (see src/sdra/generator.py).

    python scripts/generate.py          # write packs/<name>/seed.yaml and scenarios/Sxx_*.yaml
    python scripts/generate.py --check  # exit 1 if any generated file is out of date

Edit the spec, never the generated file.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).parents[1]
sys.path.insert(0, str(ROOT / "src"))

from sdra.generator import build_seed, expand_scenario, po_line_map  # noqa: E402
from sdra.pack import apply_overrides  # noqa: E402

HEADER = "# GENERATED by scripts/generate.py from {spec}. Edit the spec, not this file.\n"


class _Dumper(yaml.SafeDumper):
    def ignore_aliases(self, data) -> bool:  # write every value out; no &anchors
        return True


def _str(dumper, value: str):
    style = "|" if "\n" in value else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", value, style=style)


_Dumper.add_representer(str, _str)


def dump(data) -> str:
    return yaml.dump(data, Dumper=_Dumper, allow_unicode=True, sort_keys=False, width=110)


def outputs() -> dict[Path, str]:
    out: dict[Path, str] = {}
    for spec_path in sorted((ROOT / "packs" / "specs").glob("*.yaml")):
        spec = yaml.safe_load(spec_path.read_text(encoding="utf-8"))
        header = HEADER.format(spec=spec_path.relative_to(ROOT)) + "".join(f"# {ln}\n" for ln in spec.get("notes", []))
        out[ROOT / "packs" / spec_path.stem / "seed.yaml"] = header + dump(build_seed(spec))
    for spec_path in sorted((ROOT / "scenarios" / "specs").glob("S*.yaml")):
        spec = yaml.safe_load(spec_path.read_text(encoding="utf-8"))
        seed_path = ROOT / "packs" / spec["pack"] / "seed.yaml"
        generated_seed = out.get(seed_path)
        raw = yaml.safe_load(generated_seed if generated_seed else seed_path.read_text(encoding="utf-8"))
        lines = po_line_map(apply_overrides(raw, spec.get("seed_overrides") or []))
        out[ROOT / "scenarios" / spec_path.name] = (HEADER.format(spec=spec_path.relative_to(ROOT))
                                                    + dump(expand_scenario(spec, lines)))
    return out


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for path, text in outputs().items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != text:
            stale.append(path.relative_to(ROOT))
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8")
    for p in stale:
        print(("out of date: " if args.check else "wrote ") + str(p))
    return 1 if args.check and stale else 0


if __name__ == "__main__":
    sys.exit(main())
